#!/usr/bin/env python3
"""Regenerate ``tests/qa_trace.toml`` from the merged QA list (``qa-list.json``).

Usage::

    python3 scripts/gen_qa_trace.py PATH/TO/qa-list.json [--out tests/qa_trace.toml] [--check]

The ledger maps every QA id to how it is checked:

* ``auto``: ``unit`` | ``e2e`` | ``e2e-live`` | ``e2e-mcp`` | ``ci-gate`` | ``manual``
  (``e2e`` items split by runner: ``stdio`` -> ``e2e-mcp``, ``live`` -> ``e2e-live``);
* ``check``: ``pytest`` | ``workflow-step`` | ``checklist`` | ``script``;
* ``file`` + ``test``: the test file and function for ``pytest`` items (the script, workflow or
  checklist and a description otherwise); ``extra_tests``: further ``file::function`` node ids
  that carry the same ``@pytest.mark.qa`` marker;
* ``slow``: the item is a P2 E2E item that runs only under ``-m slow``;
* ``evidence = "release-checklist"`` on every ``manual`` item;
* ``mutants``: the mutation-plan ids (``tests/mutants.toml``) this item kills.

``tests/unit/test_qa_traceability.py`` checks the test tree against this file. ``--check`` exits
1 when the committed file differs from what the QA list generates. Standard library only.
"""

from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = REPO_ROOT / "tests" / "qa_trace.toml"
TOOL_SURFACE = REPO_ROOT / "tests" / "tool_surface.py"
# Item text that quotes a pre-1.0 tool name is fenced for the stale-name scan
# (tests/unit/test_schema_forbidden_strings.py), which reads tests/**/*.toml.
ALLOW_BEGIN = "# stale-name-scan: allow-begin"
ALLOW_END = "# stale-name-scan: allow-end"

PRIORITIES = ("P0", "P1", "P2")
AUTOMATIONS = ("unit", "e2e", "ci-gate", "manual-release")
CHECK_KINDS = ("pytest", "workflow-step", "checklist", "script")
E2E_RUNNER_AUTO = {"stdio": "e2e-mcp", "live": "e2e-live"}

HEADER = """\
# QA traceability ledger: QA id -> how the item is checked.
# GENERATED by scripts/gen_qa_trace.py from the merged QA list (qa-list.json); do not edit by
# hand. Regenerate: python3 scripts/gen_qa_trace.py PATH/TO/qa-list.json
# Checked by tests/unit/test_qa_traceability.py (QA-PKG-011).
"""


class QaListError(ValueError):
    """The QA list violates the shape this generator relies on."""


def removed_tool_names(path: Path = TOOL_SURFACE) -> tuple[str, ...]:
    """``REMOVED_TOOL_NAMES`` from ``tests/tool_surface.py``, read without importing it."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    for node in tree.body:
        if (
            isinstance(node, ast.AnnAssign)
            and isinstance(node.target, ast.Name)
            and node.target.id == "REMOVED_TOOL_NAMES"
            and node.value is not None
        ):
            names = ast.literal_eval(node.value)
            if isinstance(names, tuple) and all(isinstance(name, str) for name in names):
                return names
    raise QaListError(f"{path}: no literal REMOVED_TOOL_NAMES tuple")


def _toml_str(value: str) -> str:
    # JSON string escapes (\\, \", \n, \uXXXX for control characters) are valid TOML basic-string
    # escapes; ensure_ascii=False keeps non-BMP characters out of surrogate escapes.
    return json.dumps(value, ensure_ascii=False)


def _toml_list(values: list[str]) -> str:
    return "[" + ", ".join(_toml_str(v) for v in values) + "]"


def _auto(item: dict[str, Any]) -> str:
    automation = item["automation"]
    if automation == "manual-release":
        return "manual"
    if automation == "e2e":
        return E2E_RUNNER_AUTO.get(item["runner"], "e2e")
    return automation


def _validate(item: dict[str, Any], seen: set[str]) -> None:
    qa_id = item.get("id")
    if not isinstance(qa_id, str) or not qa_id.startswith("QA-"):
        raise QaListError(f"bad id: {qa_id!r}")
    if qa_id in seen:
        raise QaListError(f"duplicate id: {qa_id}")
    seen.add(qa_id)
    if item["priority"] not in PRIORITIES:
        raise QaListError(f"{qa_id}: bad priority {item['priority']!r}")
    if item["automation"] not in AUTOMATIONS:
        raise QaListError(f"{qa_id}: bad automation {item['automation']!r}")
    if item["check_kind"] not in CHECK_KINDS:
        raise QaListError(f"{qa_id}: bad check_kind {item['check_kind']!r}")
    if not item["test_file"] or not item["test_name"]:
        raise QaListError(f"{qa_id}: missing test_file/test_name")
    if item["check_kind"] == "pytest":
        if not item["test_file"].startswith("tests/") or not item["test_file"].endswith(".py"):
            raise QaListError(f"{qa_id}: pytest item outside tests/: {item['test_file']}")
        if not item["test_name"].isidentifier() or not item["test_name"].startswith("test_"):
            raise QaListError(f"{qa_id}: test_name is not a test function: {item['test_name']}")
    for node in item["extra_tests"]:
        path, sep, name = node.partition("::")
        if not sep or not path.startswith("tests/") or not name.isidentifier():
            raise QaListError(f"{qa_id}: bad extra test node id {node!r}")
    slow = "slow" in item["markers"]
    if slow != (item["priority"] == "P2" and item["automation"] == "e2e"):
        raise QaListError(f"{qa_id}: the slow marker must be set exactly on P2 e2e items")


def _check_slow_sharing(items: list[dict[str, Any]]) -> None:
    """One E2E test function cannot serve both a slow (P2) and a PR-gating item."""
    slow_by_node: dict[str, set[bool]] = {}
    for item in items:
        nodes = list(item["extra_tests"])
        if item["check_kind"] == "pytest":
            nodes.append(f"{item['test_file']}::{item['test_name']}")
        for node in nodes:
            if node.startswith("tests/e2e/"):
                slow_by_node.setdefault(node, set()).add("slow" in item["markers"])
    mixed = sorted(node for node, flags in slow_by_node.items() if len(flags) > 1)
    if mixed:
        raise QaListError(f"tests serving both slow and non-slow items: {mixed}")


def render(items: list[dict[str, Any]], removed_names: tuple[str, ...]) -> str:
    """Return the ``qa_trace.toml`` text for the QA list ``items``."""
    seen: set[str] = set()
    for item in items:
        _validate(item, seen)
    _check_slow_sharing(items)
    lines = [HEADER, "schema = 1", ""]
    for item in sorted(items, key=lambda entry: entry["id"]):
        auto = _auto(item)
        entry = [
            f"[items.{_toml_str(item['id'])}]",
            f"title = {_toml_str(item['title'])}",
            f"priority = {_toml_str(item['priority'])}",
            f"auto = {_toml_str(auto)}",
            f"check = {_toml_str(item['check_kind'])}",
            f"file = {_toml_str(item['test_file'])}",
            f"test = {_toml_str(item['test_name'])}",
            f"extra_tests = {_toml_list(item['extra_tests'])}",
            f"slow = {'true' if 'slow' in item['markers'] else 'false'}",
        ]
        if auto == "manual":
            entry.append('evidence = "release-checklist"')
        entry.append(f"mutants = {_toml_list(sorted(item['mutants_killed']))}")
        text = "\n".join(entry)
        if any(name in text for name in removed_names):
            entry = [ALLOW_BEGIN, *entry, ALLOW_END]
        lines.extend(entry)
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("qa_list", type=Path, help="path to the merged qa-list.json")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="ledger path to write")
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if --out differs instead of writing it"
    )
    args = parser.parse_args(argv)
    items = json.loads(args.qa_list.read_text(encoding="utf-8"))
    if not isinstance(items, list):
        print(f"{args.qa_list}: expected a JSON list of QA items", file=sys.stderr)
        return 2
    try:
        text = render(items, removed_tool_names())
    except (QaListError, KeyError) as error:
        print(f"{args.qa_list}: {error}", file=sys.stderr)
        return 2
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is stale; regenerate with scripts/gen_qa_trace.py", file=sys.stderr)
            return 1
        return 0
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({len(items)} items)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
